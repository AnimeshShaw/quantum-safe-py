"""
Envelope re-wrap interop with quantum-safe-ts 0.2.0: a message re-wrapped by TypeScript opens here, and
the TypeScript-sealed original re-wraps here to a message that opens under the new key. The vectors are
generated by quantum-safe-ts's ``scripts/gen_rewrap_vectors.mjs``.
"""

from __future__ import annotations

import json
import pathlib

import pytest

from quantum_safe.protocols.envelope import Envelope, SealedMessage
from quantum_safe.types import PublicKey, SecretKey

pytestmark = pytest.mark.requires_liboqs

VECTORS = json.loads(
    (
        pathlib.Path(__file__).resolve().parents[1]
        / "interop"
        / "vectors"
        / "ts_rewrap_vectors.json"
    ).read_text(encoding="utf-8")
)["vectors"]


@pytest.mark.parametrize("v", VECTORS, ids=[v["label"] for v in VECTORS])
def test_typescript_rewrapped_envelopes_open_and_originals_rewrap_here(v) -> None:
    aad = bytes.fromhex(v["aad"])
    plaintext = bytes.fromhex(v["plaintext"])
    new_secret = SecretKey.from_pem(v["new_secret_pem"])

    moved_by_ts = SealedMessage.from_bytes(bytes.fromhex(v["rewrapped"]))
    assert moved_by_ts.algorithm == v["to"]
    assert Envelope.open(moved_by_ts, new_secret, expected_aad=aad) == plaintext

    original = SealedMessage.from_bytes(bytes.fromhex(v["original"]))
    assert original.algorithm == v["from"]
    mine = Envelope.rewrap(
        original,
        SecretKey.from_pem(v["old_secret_pem"]),
        PublicKey.from_pem(v["new_public_pem"]),
        expected_aad=aad,
    )
    assert mine.algorithm == v["to"] and mine.aad == aad
    assert Envelope.open(mine, new_secret, expected_aad=aad) == plaintext


def test_vectors_cover_hybrids_with_both_classical_halves() -> None:
    assert {v["from"].split("+")[0] for v in VECTORS} == {"X25519", "P-256"}
