"""
LMS signatures made by quantum-safe-ts's ``LmsSigner`` (Node.js, write-ahead state) verify with this
library's independent LMS implementation (pyhsslms), for every Winternitz parameter and for trees of
height 5 and 10. The vectors are generated by quantum-safe-ts's ``scripts/gen_lms_signer_vectors.mjs``.
"""

from __future__ import annotations

import json
import pathlib

import pytest

pytest.importorskip("pyhsslms", reason="needs the [lms] extra (pyhsslms)")

from quantum_safe.signatures.stateful import verify  # noqa: E402

VECTORS = json.loads(
    (
        pathlib.Path(__file__).resolve().parents[1]
        / "interop"
        / "vectors"
        / "ts_lms_signer_vectors.json"
    ).read_text(encoding="utf-8")
)["vectors"]


@pytest.mark.parametrize("vector", VECTORS, ids=[v["parameter_set"] for v in VECTORS])
def test_typescript_lms_signatures_verify(vector) -> None:
    # quantum-safe-ts writes HSS (RFC 8554 section 6): u32(levels) || LMS public key, and
    # u32(levels - 1) || LMS signature. With one level the LMS parts follow a 4-byte count.
    hss_key = bytes.fromhex(vector["public_key"])
    assert hss_key[:4] == (1).to_bytes(4, "big")
    public_key = hss_key[4:]
    for case in vector["cases"]:
        message = bytes.fromhex(case["message"])
        hss_signature = bytes.fromhex(case["signature"])
        assert hss_signature[:4] == (0).to_bytes(4, "big")
        signature = hss_signature[4:]
        assert verify(public_key, message, signature) is True
        assert verify(public_key, message + b"x", signature) is False


def test_vectors_cover_every_winternitz_parameter() -> None:
    assert {v["winternitz"] for v in VECTORS} == {1, 2, 4, 8}
    assert {v["height"] for v in VECTORS} == {5, 10}
